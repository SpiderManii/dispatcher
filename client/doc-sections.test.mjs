// Run with: node --experimental-transform-types --test
import assert from "node:assert/strict";
import { test } from "node:test";
import { bodyOf, cardTitle, groupSections, preview, sectionLabel, splitSections } from "./doc-sections.ts";

test("splits at # and ## and keeps the heading with its body", () => {
  const parts = splitSections("# 身份\n你是调度员\n\n## 负责的项目\n- a\n- b\n\n## 会话边界\n不越界");
  assert.deepEqual(parts.map((part) => part.title), ["身份", "负责的项目", "会话边界"]);
  assert.equal(parts[1].markdown, "## 负责的项目\n- a\n- b");
});

test("text before the first heading is an overview, and empty parts are dropped", () => {
  const parts = splitSections("前言一句\n\n## 一\n内容");
  assert.deepEqual(parts.map((part) => part.title), ["概览", "一"]);
  assert.deepEqual(splitSections("## 只有标题\n").map((part) => part.title), ["只有标题"]);
});

test("a # line inside a code fence is not a heading", () => {
  const parts = splitSections("## 命令\n```sh\n# 注释不是标题\nls\n```\n\n## 下一节\nx");
  assert.deepEqual(parts.map((part) => part.title), ["命令", "下一节"]);
  assert.ok(parts[0].markdown.includes("# 注释不是标题"));
});

test("### stays inside its section", () => {
  const parts = splitSections("## 大\n### 小\n内容");
  assert.equal(parts.length, 1);
  assert.ok(parts[0].markdown.includes("### 小"));
});

test("labels drop a trailing note and cut long titles", () => {
  assert.equal(sectionLabel("通用调度规则（原文快照，来源：/Users/x/调度员.md）"), "通用调度规则");
  assert.equal(sectionLabel("1. 硬规矩（每次必守）"), "1. 硬规矩");
  assert.equal(sectionLabel("一个特别特别特别特别特别长的标题啊啊啊"), "一个特别特别特别特别特别长的标…");
  assert.equal(sectionLabel("（全是括号）"), "（全是括号）");
});

test("levels follow the heading marks, so an outline can indent ## under #", () => {
  const parts = splitSections("# 一\n正文\n## 一点一\n内容\n# 二\n内容");
  assert.deepEqual(parts.map((part) => [part.title, part.level]), [["一", 1], ["一点一", 2], ["二", 1]]);
});

test("# headings are groups and ## headings are the cards in them", () => {
  const long = "字".repeat(400);
  const groups = groupSections(splitSections(`前言\n\n# 身份\n${long}\n## 项目\n甲\n## 边界\n乙\n# 规则\n${long}\n## 1. 硬规矩\n丙`));
  // The one-line preamble is a short note on its own, so it rides along as the first card of the group after it.
  assert.deepEqual(groups.map((group) => group.title), ["身份", "规则"]);
  assert.deepEqual(groups[0].cards.map((card) => card.title), ["概览", "身份", "项目", "边界"]);
  assert.deepEqual(groups[1].cards.map((card) => card.title), ["规则", "1. 硬规矩"]);
});

test("a group that is one short note folds into the next group", () => {
  const groups = groupSections(splitSections("# 通用规则\n来源：某文件\n# 调度员规则\n总则\n## 1. 硬规矩\n甲\n## 2. 角色\n乙"));
  assert.deepEqual(groups.map((group) => group.title), ["调度员规则"]);
  assert.deepEqual(groups[0].cards.map((card) => card.title), ["通用规则", "调度员规则", "1. 硬规矩", "2. 角色"]);
});

test("a heading with no text and no children makes no group", () => {
  assert.deepEqual(groupSections(splitSections("# 空\n# 有内容\n文字很多".padEnd(500, "。"))).map((group) => group.title), ["有内容"]);
});

test("card body drops its own heading line; titles split off a leading number", () => {
  const [section] = splitSections("## 3. 模型分工\n- 拆分：Codex\n- 后端：Codex");
  assert.equal(bodyOf(section), "- 拆分：Codex\n- 后端：Codex");
  assert.deepEqual(cardTitle("3. 模型分工"), { number: "3", text: "模型分工" });
  assert.deepEqual(cardTitle("负责的项目"), { number: null, text: "负责的项目" });
});

test("preview is plain text from the first lines, without markup or code", () => {
  assert.equal(preview("## 标题\n- **拆分**：用 `Codex` 出计划\n- 后端：见[文档](http://x)\n```sh\nls\n```\n- 第三行"), "拆分：用 Codex 出计划 后端：见文档 第三行");
  assert.equal(preview("字".repeat(300), 20), `${"字".repeat(19)}…`);
});

test("preview skips comments, shows a table as a row count", () => {
  assert.equal(preview("<!-- generated by plugin -->\n<!-- 由插件生成 -->\n你是调度员"), "你是调度员");
  assert.equal(preview("| 项目 | 名称 |\n|---|---|\n| a | b |\n| c | d |"), "表格 · 2 行");
  assert.equal(preview("说明\n| 项目 |\n|---|\n| a |"), "说明");
});

test("a section of only HTML comments makes no card", () => {
  const groups = groupSections(splitSections("<!-- generated -->\n# 规则\n" + "字".repeat(400) + "\n## 空节\n<!-- 只有注释 -->\n## 有内容\n甲"));
  assert.deepEqual(groups[0].cards.map((card) => card.title), ["规则", "有内容"]);
});
